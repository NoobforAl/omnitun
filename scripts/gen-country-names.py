#!/usr/bin/env python3
"""Writes app/lib/state/country_names.dart: the names of the countries the app lists,
in the app's languages, from the Unicode CLDR (through the Babel package).

    pip install babel
    python scripts/gen-country-names.py

English names are not generated: they are the table in countries.dart, which the
guess of a server's country also matches against.
"""
import os
import re
import sys

from babel import Locale

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LANGUAGES = ["fa", "ru", "zh", "ar"]


def codes():
    src = open(os.path.join(ROOT, "app", "lib", "state", "countries.dart"), encoding="utf-8").read()
    table = re.search(r"const _table = '''(.*?)'''", src, re.S).group(1).replace("\n", "")
    return sorted(e[:2] for e in table.split("|") if ":" in e)


def main():
    wanted = codes()
    out = [
        "// Generated by scripts/gen-country-names.py from the Unicode CLDR; do not edit.",
        "// Unicode data files and software are under the Unicode License v3:",
        "// https://www.unicode.org/license.txt",
        "library;",
        "",
        "/// Country names by language and ISO 3166-1 alpha-2 code.",
        "const countryNamesByLanguage = <String, Map<String, String>>{",
    ]
    for lang in LANGUAGES:
        names = Locale(lang).territories
        out.append("  '%s': {" % lang)
        for code in wanted:
            name = names.get(code)
            if not name:
                print("no %s name for %s" % (lang, code), file=sys.stderr)
                continue
            out.append("    '%s': '%s'," % (code, name.replace("\\", "\\\\").replace("'", "\\'")))
        out.append("  },")
    out.append("};")
    path = os.path.join(ROOT, "app", "lib", "state", "country_names.dart")
    open(path, "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
    print("%d countries in %d languages" % (len(wanted), len(LANGUAGES)))


if __name__ == "__main__":
    main()
